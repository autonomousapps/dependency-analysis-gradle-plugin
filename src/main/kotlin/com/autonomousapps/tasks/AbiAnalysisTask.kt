package com.autonomousapps.tasks

import com.autonomousapps.TASK_GROUP_DEP
import com.autonomousapps.internal.AbiExclusions
import com.autonomousapps.internal.kotlin.computeAbi
import com.autonomousapps.internal.utils.*
import com.autonomousapps.model.internal.kmp.SourceSetFiles
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.ProjectLayout
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.*
import org.gradle.workers.WorkAction
import org.gradle.workers.WorkParameters
import org.gradle.workers.WorkerExecutor
import javax.inject.Inject

@CacheableTask
public abstract class AbiAnalysisTask @Inject constructor(
  private val workerExecutor: WorkerExecutor,
  private val layout: ProjectLayout,
) : AndroidClassesTask() {

  init {
    group = TASK_GROUP_DEP
    description = "Produces a report of the ABI of this project"
  }

  /** Source files from which the class files were generated. May be empty. */
  @get:InputFiles
  @get:PathSensitive(PathSensitivity.RELATIVE)
  public abstract val sourceFiles: ConfigurableFileCollection

  /** Class files generated by any JVM source (Java, Kotlin, Groovy, etc.). May be empty. */
  @get:PathSensitive(PathSensitivity.RELATIVE)
  @get:InputFiles
  public abstract val classes: ConfigurableFileCollection

  /** `kotlin-metadata-jvm`, added to the isolated worker classpath. */
  @get:PathSensitive(PathSensitivity.RELATIVE)
  @get:InputFiles
  public abstract val kotlinMetadataClasspath: ConfigurableFileCollection

  /** Only available in KMP projects. */
  @get:Optional
  @get:PathSensitive(PathSensitivity.RELATIVE)
  @get:InputFile
  public abstract val kmpSources: RegularFileProperty

  @get:Optional
  @get:Input
  public abstract val exclusions: Property<String>

  @get:OutputFile
  public abstract val output: RegularFileProperty

  @get:OutputFile
  public abstract val abiDump: RegularFileProperty

  @TaskAction
  public fun action() {
    workerExecutor.classLoaderIsolation {
      // kotlin-metadata-jvm is not on the main plugin classpath (issue 1671); add it for the isolated worker only.
      it.classpath.from(kotlinMetadataClasspath)
    }.submit(AbiAnalysisWorkAction::class.java) {
      it.projectDir.set(layout.projectDirectory)
      it.sourceFiles.setFrom(this@AbiAnalysisTask.sourceFiles.asFileTree)
      // JVM projects
      it.classFiles.setFrom(classes.asFileTree.filterToClassFiles().files)
      // Android projects
      it.classFiles.from(androidClassFiles())
      // KMP projects
      it.kmpSources.set(kmpSources)

      it.exclusions.set(exclusions)
      it.output.set(output)
      it.abiDump.set(abiDump)
    }
  }

  public interface AbiAnalysisParameters : WorkParameters {
    public val projectDir: DirectoryProperty
    public val sourceFiles: ConfigurableFileCollection
    public val classFiles: ConfigurableFileCollection
    public val kmpSources: RegularFileProperty
    public val exclusions: Property<String>
    public val output: RegularFileProperty
    public val abiDump: RegularFileProperty
  }

  public abstract class AbiAnalysisWorkAction : WorkAction<AbiAnalysisParameters> {

    override fun execute() {
      val output = parameters.output.getAndDelete()
      val outputAbiDump = parameters.abiDump.getAndDelete()

      val sourceFiles = parameters.sourceFiles.files
      val classFiles = parameters.classFiles.files
      val kmpSources = parameters.kmpSources.fromNullableJsonSet<SourceSetFiles>()
      val exclusions = parameters.exclusions.orNull?.fromJson<AbiExclusions>() ?: AbiExclusions.NONE

      val explodingAbi = computeAbi(
        projectDir = parameters.projectDir.get().asFile,
        classFiles = classFiles,
        sourceFiles = sourceFiles,
        kmpSources = kmpSources,
        exclusions = exclusions,
        abiDumpFile = outputAbiDump,
      )

      output.bufferWriteJsonSet(explodingAbi)
    }
  }
}
